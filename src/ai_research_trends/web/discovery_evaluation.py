"""Prepare and score an optional human Paper Discovery relevance review.

No relevance labels or empirical scores are generated by ``prepare``.
``score`` accepts only completed 0/1/2 annotations supplied by a reviewer.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import math
import re
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from ai_research_trends.preprocessing.validate_tables import file_sha256
from ai_research_trends.web.paper_discovery import PaperDiscovery
from ai_research_trends.web.service import discovery_path

DEFAULT_QUERIES = Path("config/discovery_evaluation_queries.jsonl")
DEFAULT_OUTPUT = Path("data/application/paper_discovery_evaluation")
FIELDS = ("query_id", "query_title", "query_abstract", "rank", "work_id", "paper_title", "relevance")
FIXED_FIELDS = FIELDS[:-1]


def _fixed_rows_sha256(rows: list[dict[str, Any]]) -> str:
    """Bind every displayed query and paper field while allowing grade edits."""
    fixed = [[str(row[field]) for field in FIXED_FIELDS] for row in rows]
    encoded = json.dumps(fixed, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


def load_queries(path: Path, *, min_queries: int = 15, max_queries: int = 30) -> list[dict[str, str]]:
    """Read public, illustrative research ideas; never load test labels."""
    queries: list[dict[str, str]] = []
    seen: set[str] = set()
    for line_number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip():
            continue
        record = json.loads(line)
        if (not isinstance(record, dict) or set(record) != {"query_id", "title", "abstract"}
                or not all(isinstance(value, str) for value in record.values())):
            raise ValueError(f"Invalid query at line {line_number}")
        key = record["query_id"]
        if not re.fullmatch(r"Q[0-9]{2,3}", key) or key in seen:
            raise ValueError(f"Duplicate or invalid query ID: {key}")
        # Use the same validation as the live search UI, before creating output.
        if len(record["title"].split()) < 5 or len(record["title"]) < 20:
            raise ValueError(f"Query {key} needs a descriptive title")
        if len(record["abstract"].split()) < 8 or len(record["abstract"]) < 50:
            raise ValueError(f"Query {key} needs a usable abstract")
        seen.add(key)
        queries.append(record)
    if not min_queries <= len(queries) <= max_queries:
        raise ValueError(f"Expected {min_queries}–{max_queries} queries; found {len(queries)}")
    return queries


def prepare_package(index_dir: Path, query_path: Path, output_dir: Path) -> dict[str, Any]:
    """Freeze top-five result identities in a local, blank review sheet."""
    if output_dir.exists():
        raise FileExistsError(output_dir)
    index = PaperDiscovery(index_dir)
    queries = load_queries(query_path)
    rows: list[dict[str, Any]] = []
    for query in queries:
        result = index.search(query["title"], query["abstract"], top_k=5)
        for rank, paper in enumerate(result["items"], 1):
            rows.append({"query_id": query["query_id"], "query_title": query["title"],
                         "query_abstract": query["abstract"], "rank": rank,
                         "work_id": paper["work_id"], "paper_title": paper["title"],
                         "relevance": ""})
    output_dir.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".discovery_review_", dir=output_dir.parent) as temporary:
        stage = Path(temporary)
        sheet = stage / "judgments.csv"
        with sheet.open("w", encoding="utf-8", newline="") as handle:
            writer = csv.DictWriter(handle, fieldnames=FIELDS)
            writer.writeheader()
            writer.writerows(rows)
        manifest = {"version": 1, "status": "awaiting_human_judgments",
                    "created_at_utc": datetime.now(timezone.utc).isoformat(),
                    "query_ids": [query["query_id"] for query in queries],
                    "query_count": len(queries), "retrieved_pairs": len(rows),
                    "no_result_queries": [query["query_id"] for query in queries
                                          if not any(row["query_id"] == query["query_id"] for row in rows)],
                    "pairs": [[row["query_id"], row["rank"], row["work_id"]] for row in rows],
                    "fixed_rows_sha256": _fixed_rows_sha256(rows),
                    "source": {"query_sha256": file_sha256(query_path),
                               "index_manifest_sha256": file_sha256(index_dir / "manifest.json"),
                               "index_scope": index.manifest["scope"]},
                    "blank_sheet_sha256": file_sha256(sheet)}
        (stage / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
        stage.rename(output_dir)
    return manifest


def ranking_metrics(relevance: list[int], *, k: int = 5) -> tuple[float, float]:
    """P@k treats only grade 2 as relevant; nDCG uses graded gain 2^r−1."""
    if k != 5 or len(relevance) > k or any(value not in (0, 1, 2) for value in relevance):
        raise ValueError("Invalid relevance grades or cutoff")
    precision = sum(value == 2 for value in relevance) / k
    dcg = sum((2**grade - 1) / math.log2(rank + 2)
              for rank, grade in enumerate(relevance))
    ideal = sum((2**grade - 1) / math.log2(rank + 2)
                for rank, grade in enumerate(sorted(relevance, reverse=True)))
    return precision, dcg / ideal if ideal else 0.0


def score_package(run_dir: Path, *, annotator_id: str, output: Path | None = None) -> dict[str, Any]:
    """Score a completed sheet; refuse partial or altered retrieval identities."""
    if not re.fullmatch(r"[A-Za-z0-9_-]{2,40}", annotator_id):
        raise ValueError("Invalid annotator identifier")
    manifest = json.loads((run_dir / "manifest.json").read_text(encoding="utf-8"))
    if manifest.get("version") != 1 or manifest.get("status") != "awaiting_human_judgments":
        raise ValueError("Unsupported review package")
    sheet = run_dir / "judgments.csv"
    with sheet.open(encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle)
        if reader.fieldnames != list(FIELDS):
            raise ValueError("Review sheet columns changed")
        rows = list(reader)
    pairs = [[row["query_id"], int(row["rank"]), row["work_id"]] for row in rows]
    if pairs != manifest["pairs"] or len(rows) != manifest["retrieved_pairs"]:
        raise ValueError("Review sheet retrieval identities or order changed")
    if _fixed_rows_sha256(rows) != manifest["fixed_rows_sha256"]:
        raise ValueError("Review sheet query or result text changed")
    by_query: dict[str, list[int]] = {query_id: [] for query_id in manifest["query_ids"]}
    for row in rows:
        if row["relevance"] not in {"0", "1", "2"}:
            raise ValueError("Human relevance judgments are missing or invalid")
        by_query[row["query_id"]].append(int(row["relevance"]))
    if not by_query or any(len(grades) > 5 for grades in by_query.values()):
        raise ValueError("Invalid query denominator")
    values = [ranking_metrics(by_query[query_id]) for query_id in manifest["query_ids"]]
    result = {"status": "scored_from_supplied_annotations", "annotator_id_self_reported": annotator_id,
              "scored_at_utc": datetime.now(timezone.utc).isoformat(),
              "query_count": len(values), "retrieved_pairs": len(rows),
              "queries_with_no_results": len(manifest["no_result_queries"]),
              "precision_at_5_grade_2_mean": sum(item[0] for item in values) / len(values),
              "ndcg_at_5_graded_mean": sum(item[1] for item in values) / len(values),
              "annotation_sha256": file_sha256(sheet),
              "package_manifest_sha256": file_sha256(run_dir / "manifest.json"),
              "warning": "Annotator identity and human independence are self-reported, not verified by this script."}
    target = output or run_dir / f"scores_{annotator_id}.json"
    with target.open("x", encoding="utf-8") as handle:
        json.dump(result, handle, indent=2)
        handle.write("\n")
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    prepare = sub.add_parser("prepare", help="Create blank top-five judgments; no relevance scores")
    prepare.add_argument("--index-dir", type=Path, default=discovery_path())
    prepare.add_argument("--queries", type=Path, default=DEFAULT_QUERIES)
    prepare.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT)
    score = sub.add_parser("score", help="Score a fully human-annotated sheet")
    score.add_argument("--run-dir", type=Path, default=DEFAULT_OUTPUT)
    score.add_argument("--annotator-id", required=True)
    score.add_argument("--output", type=Path)
    args = parser.parse_args(argv)
    result = (prepare_package(args.index_dir, args.queries, args.output_dir)
              if args.command == "prepare" else
              score_package(args.run_dir, annotator_id=args.annotator_id, output=args.output))
    print(json.dumps({key: value for key, value in result.items()
                      if key not in {"pairs", "query_ids"}}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
